#!/usr/bin/env sh
# Copies the extension's code and fonts into website/ so the landing page runs
# the real inspector. Run after changing extension/lib or extension/content.
set -e
cd "$(dirname "$0")/.."
mkdir -p website/vendor website/fonts website/img
cp extension/lib/core.js website/vendor/core.js
{
  echo '// Generated by scripts/build-site.sh from extension/content/inspector.js. Do not edit.'
  echo '(function (chrome) {'
  cat extension/content/inspector.js
  echo '})(window.SpacingDemoChrome);'
} > website/vendor/inspector.js
cp extension/fonts/Geist-Variable.woff2 extension/fonts/GeistMono-Variable.woff2 website/fonts/
cp extension/icons/icon128.png website/img/icon128.png
echo "Synced extension code into website/"
